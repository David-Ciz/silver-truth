#!/usr/bin/env python3
"""
build_ranker_benchmark_table.py
--------------------------------
Reads configs/ranker_benchmark.yaml and scans
hpc_results/ranker_benchmark/{method}/{dataset}/{variant}/{fold}/ranker_pruned_fusion_comparison.csv
to collect mean_iou for every (method, fold) combination.

Outputs:
    hpc_results/ranker_benchmark/benchmark_table.csv   — pivot table
    hpc_results/ranker_benchmark/benchmark_table.md    — markdown for docs/papers

Usage:
    python scripts/build_ranker_benchmark_table.py
    python scripts/build_ranker_benchmark_table.py --config configs/ranker_benchmark.yaml
    python scripts/build_ranker_benchmark_table.py --output-prefix results/my_table
"""

import argparse
from pathlib import Path

import pandas as pd
import yaml


RESULT_FILENAME = "ranker_pruned_fusion_comparison.csv"


def load_config(config_path: Path) -> dict:
    with open(config_path) as f:
        return yaml.safe_load(f)


def collect_result(out_dir: Path, method: dict) -> float | None:
    """Read mean_iou from a completed benchmark run directory."""
    result_file = out_dir / RESULT_FILENAME
    if not result_file.exists():
        return None

    df = pd.read_csv(result_file)

    # The comparison CSV has a row per fusion model, look for SIMPLE or best
    if "model" in df.columns and "mean_iou" in df.columns:
        simple_rows = df[df["model"].str.upper() == "SIMPLE"]
        if not simple_rows.empty:
            return float(simple_rows.iloc[0]["mean_iou"])
        # Fallback: max across all models
        return float(df["mean_iou"].max())

    # Some older outputs just have one row
    if "mean_iou" in df.columns:
        return float(df["mean_iou"].iloc[0])

    return None


def output_dir_for(root: Path, method_name: str, fold_def: dict) -> Path:
    return (
        root
        / method_name
        / fold_def["dataset"]
        / fold_def["variant"]
        / fold_def["fold"]
    )


def build_table(cfg: dict, repo_root: Path) -> pd.DataFrame:
    benchmark = cfg["benchmark"]
    output_root = repo_root / benchmark["output_root"]
    folds = cfg["folds"]
    methods = cfg["methods"]

    rows = []
    for fold_def in folds:
        fold_id = fold_def["id"]
        row = {
            "dataset": fold_def["dataset"],
            "fold": fold_def["fold"],
            "fold_id": fold_id,
        }
        for method in methods:
            out_dir = output_dir_for(output_root, method["name"], fold_def)
            value = collect_result(out_dir, method)
            row[method["name"]] = value
        rows.append(row)

    return pd.DataFrame(rows)


def pivot_display(df: pd.DataFrame, cfg: dict) -> pd.DataFrame:
    """Reshape to a clean display table with method labels."""
    method_name_to_label = {m["name"]: m["label"] for m in cfg["methods"]}
    method_names = [m["name"] for m in cfg["methods"]]

    display = df[["fold_id"]].copy()
    for name in method_names:
        if name in df.columns:
            label = method_name_to_label.get(name, name)
            display[label] = df[name].map(
                lambda v: f"{v:.6f}" if v is not None and pd.notna(v) else "—"
            )
    return display


def render_markdown(df_raw: pd.DataFrame, cfg: dict) -> str:
    method_names = [m["name"] for m in cfg["methods"]]
    method_labels = {m["name"]: m["label"] for m in cfg["methods"]}

    lines = []
    lines.append("# Ranker Benchmark Results\n")
    lines.append("Generated by `scripts/build_ranker_benchmark_table.py`.\n")

    # Per-dataset sections
    for dataset in df_raw["dataset"].unique():
        df_ds = df_raw[df_raw["dataset"] == dataset].copy()
        lines.append(f"## {dataset}\n")

        # Header
        headers = ["Fold"] + [method_labels.get(n, n) for n in method_names if n in df_raw.columns]
        lines.append("| " + " | ".join(headers) + " |")
        lines.append("| " + " | ".join(["---"] * len(headers)) + " |")

        for _, row in df_ds.iterrows():
            cells = [row["fold"]]
            for name in method_names:
                if name in row:
                    v = row[name]
                    cells.append(f"{v:.6f}" if v is not None and pd.notna(v) else "—")
            lines.append("| " + " | ".join(cells) + " |")

        # Mean row
        cells = ["**mean**"]
        for name in method_names:
            if name in df_ds.columns:
                vals = df_ds[name].dropna()
                cells.append(f"**{vals.mean():.6f}**" if len(vals) > 0 else "—")
        lines.append("| " + " | ".join(cells) + " |")
        lines.append("")

    # Overall mean row across all folds
    lines.append("## Overall mean (all folds)\n")
    headers = ["Method", "Mean IoU"]
    lines.append("| " + " | ".join(headers) + " |")
    lines.append("| --- | --- |")
    for name in method_names:
        if name in df_raw.columns:
            vals = df_raw[name].dropna()
            label = method_labels.get(name, name)
            if len(vals) > 0:
                lines.append(f"| {label} | **{vals.mean():.6f}** |")
            else:
                lines.append(f"| {label} | — |")
    lines.append("")

    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description="Build ranker benchmark comparison table")
    parser.add_argument(
        "--config",
        default="configs/ranker_benchmark.yaml",
        help="Path to registry YAML",
    )
    parser.add_argument(
        "--output-prefix",
        default=None,
        help="Output prefix for CSV/MD files (default: hpc_results/ranker_benchmark/benchmark_table)",
    )
    args = parser.parse_args()

    repo_root = Path(__file__).resolve().parent.parent
    config_path = repo_root / args.config
    cfg = load_config(config_path)

    benchmark = cfg["benchmark"]
    output_root = repo_root / benchmark["output_root"]

    if args.output_prefix:
        out_prefix = Path(args.output_prefix)
    else:
        out_prefix = output_root / "benchmark_table"

    out_prefix.parent.mkdir(parents=True, exist_ok=True)

    print(f"Reading config: {config_path}")
    print(f"Scanning: {output_root}")

    df = build_table(cfg, repo_root)

    # Raw CSV (numeric)
    csv_path = out_prefix.with_suffix(".csv")
    df.to_csv(csv_path, index=False)
    print(f"\nSaved raw CSV: {csv_path}")

    # Markdown
    md_text = render_markdown(df, cfg)
    md_path = out_prefix.with_suffix(".md")
    md_path.write_text(md_text, encoding="utf-8")
    print(f"Saved markdown: {md_path}")

    # Console summary
    print("\n" + "=" * 70)
    print(md_text)
    print("=" * 70)

    # Warn about missing results
    method_names = [m["name"] for m in cfg["methods"]]
    fold_ids = [f["id"] for f in cfg["folds"]]
    missing = []
    for _, row in df.iterrows():
        for name in method_names:
            if name in row and (row[name] is None or pd.isna(row[name])):
                missing.append(f"  {name} × {row['fold_id']}")
    if missing:
        print("Missing results (run `python scripts/run_ranker_benchmark.py`):")
        for m in missing:
            print(m)


if __name__ == "__main__":
    main()
